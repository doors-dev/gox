package lsp

import (
	"encoding/json"

	"github.com/bytedance/sonic/ast"
	"github.com/doors-dev/gox/internal/common"
	jsonrpc2 "github.com/doors-dev/gox/internal/jsonrpc"
	"github.com/doors-dev/gox/internal/workspace"
)

func initClientNotifs(sess *session, on func(on onNotif, m ...method)) {
	on(func(n notifier, j Json) {
		doc, kind, err := jsonDoc.open(sess.man(), j)
		if err != nil {
			n.err(common.FromErr(jsonrpc2.ErrInvalidParams, err))
			return
		}
		if kind == workspace.KindUnknown {
			n.forward()
			return
		}
		version, err := jsonDoc.getVersion(j)
		if err != nil {
			n.err(common.FromErr(jsonrpc2.ErrInvalidParams, err))
			return
		}
		text, err := jsonDoc.getText(j)
		if err != nil {
			n.err(common.FromErr(jsonrpc2.ErrInvalidParams, err))
			return
		}
		if doc.Err() != nil {
			n.err(common.FromErr(jsonrpc2.ErrUnknown, doc.Err()))
			return
		}
		switch kind {
		case workspace.KindSource:
			upd, err := doc.SourceUpdate(text)
			if err != nil {
				n.err(common.FromErr(jsonrpc2.ErrInternal, err))
				return
			}
			doc.SourceOpen(int32(version))
			insertGoxImport(sess, doc)
			if !doc.TargetIsOpened() {
				jsonDoc.setAsTarget(j, doc)
				n.notify(j)
				return
			}
			// gopls already has the .x.go open (via its buffer), and edits to
			// that buffer are never forwarded. Replace gopls's copy with the
			// generated code, under the source version: gopls's versioned
			// edits on the .x.go are mapped back to the source with it.
			sess.notifGo(didChange, jsonGenerator.newFullChange(doc.TargetFile().URI(), int32(version), doc.TargetContent()))
			if upd {
				sess.callClient(
					applyEdit,
					jsonGenerator.newUpdateEdit(doc.TargetFile().URI(), doc.TargetContent(), "synced with the .gox file"),
				)
			}
		case workspace.KindTarget:
			doc.TargetOpen(int32(version))
			sourceOpened := doc.SourceIsOpened()
			if !sourceOpened {
				// The buffer text may be stale (e.g. generated by another GoX
				// version); gopls gets the generated code instead.
				jsonDoc.setAsTarget(j, doc)
				jsonDoc.setVersion(j, 0)
				n.notify(j)
			}
			// With the source open, gopls is already in sync and its
			// diagnostics are stored; send them once the buffer matches.
			publishDiag := func() {
				if !sourceOpened || !doc.TargetIsOpened() {
					return
				}
				if diag := doc.GetDiag(); diag != nil {
					sess.notifClient(publishDiagnostics, diag)
				}
			}
			if text == doc.TargetContent() {
				publishDiag()
				return
			}
			sess.callClientHandle(
				applyEdit,
				jsonGenerator.newUpdateEdit(doc.TargetFile().URI(), doc.TargetContent(), "synced with the .gox file"),
				func(r Response) {
					if r.Err == nil && editApplied(r) {
						publishDiag()
					}
				})
		}
	}, didOpen)

	on(func(n notifier, j Json) {
		doc, kind, err := jsonDoc.get(sess.man(), j, true)
		if err != nil {
			n.err(common.FromErr(jsonrpc2.ErrInvalidParams, err))
			return
		}
		if kind == workspace.KindUnknown {
			n.forward()
			return
		}
		if doc == nil && kind == workspace.KindTarget {
			sess.showWarn("This generated file does not belong to the current workspace.")
			n.forward()
			return
		}
		if doc.Err() != nil {
			n.err(common.FromErr(jsonrpc2.ErrUnknown, doc.Err()))
			return
		}
		if kind == workspace.KindSource && !doc.SourceIsOpened() {
			n.err(errSourceNotOpened)
			return
		}
		switch kind {
		case workspace.KindSource:
			changes, err := jsonChanges.getChanges(j)
			if err != nil {
				n.err(common.FromErr(jsonrpc2.ErrInvalidParams, err))
				return
			}
			updated := false
			for _, change := range changes {
				var upd bool
				if change.HasRange {
					upd, err = doc.SourcePatch(sess.enc(), change.Range, change.Text)
					updated = updated || upd
				} else {
					upd, err = doc.SourceUpdate(change.Text)
					updated = updated || upd
				}
				if err != nil {
					break
				}
			}
			if err != nil {
				n.err(common.FromErr(jsonrpc2.ErrInternal, err))
				return
			}
			if updated {
				doc.Assemble()
			}
			jsonDoc.setAsTarget(j, doc)
			jsonChanges.setUpdate(j, doc.TargetContent())
			n.notify(j)
			if updated && doc.TargetIsOpened() {
				sess.callClient(
					applyEdit,
					jsonGenerator.newUpdateEdit(doc.TargetFile().URI(), doc.TargetContent(), ""),
				)
			}
			if updated {
				insertGoxImport(sess, doc)
			}
		case workspace.KindTarget:
			return
		}
	}, didChange)

	on(func(n notifier, j Json) {
		doc, kind, err := jsonDoc.get(sess.man(), j, true)
		if err != nil {
			n.err(common.FromErr(jsonrpc2.ErrInvalidParams, err))
			return
		}
		if doc == nil && kind == workspace.KindTarget {
			sess.showWarn("This generated file does not belong to the current workspace.")
			n.forward()
			return
		}
		if kind == workspace.KindUnknown {
			n.forward()
			return
		}
		if doc.Err() != nil {
			n.err(common.FromErr(jsonrpc2.ErrUnknown, doc.Err()))
			return
		}
		if kind == workspace.KindTarget {
			needUpd, err := doc.CheckTarget()
			if err != nil {
				n.err(common.FromErr(jsonrpc2.ErrInternal, err))
				return
			}
			overlay := doc.SourceIsOpened() || doc.TargetIsOpened()
			if !needUpd {
				if overlay {
					n.forward()
				}
				return
			}
			if err := doc.TargetWrite(); err != nil {
				n.err(common.FromErr(jsonrpc2.ErrInternal, err))
				return
			}
			sess.showWarn("Generated file changes were reverted on save. Edit the .gox source, or rename .x.go to .go to edit this file directly.")
			text := j.Get("text")
			if text.Exists() {
				j.Set("text", ast.NewString(doc.TargetContent()))
			}
			if overlay {
				n.notify(j)
			}
			return
		}
		if !doc.SourceIsOpened() {
			n.err(errSourceNotOpened)
			return
		}
		err = doc.Save()
		if err != nil {
			n.err(common.FromErr(jsonrpc2.ErrInternal, err))
			return
		}
		jsonDoc.setAsTarget(j, doc)
		n.notify(j)
	}, didSave)

	on(func(n notifier, j Json) {
		doc, kind, err := jsonDoc.get(sess.man(), j, false)
		if err != nil {
			n.err(common.FromErr(jsonrpc2.ErrInvalidParams, err))
			return
		}
		if kind == workspace.KindUnknown {
			n.forward()
			return
		}
		if doc == nil {
			return
		}
		switch kind {
		case workspace.KindSource:
			if !doc.SourceIsOpened() {
				return
			}
			reverted := doc.SourceClose()
			if !doc.TargetIsOpened() {
				jsonDoc.setAsTarget(j, doc)
				n.notify(j)
				return
			}
			if reverted {
				sess.notifGo(didChange, jsonGenerator.newFullChange(doc.TargetFile().URI(), 0, doc.TargetContent()))
				sess.callClient(
					applyEdit,
					jsonGenerator.newUpdateEdit(doc.TargetFile().URI(), doc.TargetContent(), "synced with the .gox file"),
				)
			}
		case workspace.KindTarget:
			if !doc.TargetIsOpened() && doc.Err() != nil {
				return
			}
			doc.TargetClose()
			if doc.SourceIsOpened() {
				return
			}
			n.forward()
		}
	}, didClose)

	on(func(n notifier, j Json) {
		added, removed, err := jsonInit.getWorkspaceChanges(j)
		if err != nil {
			n.err(common.FromErr(jsonrpc2.ErrInvalidParams, err))
			return
		}
		for _, uri := range added {
			sess.addWorkspace(uri)
		}
		for _, uri := range removed {
			sess.removeWorkspace(uri)
		}
		n.forward()
	}, didChangeWorkspaceFolders)

}

var errSourceNotOpened = common.NewErr(jsonrpc2.ErrUnknown, "GoX is not tracking this buffer: it was opened outside the workspace folders or could not be loaded. Close and reopen the file.")

func editApplied(r Response) bool {
	var res struct {
		Applied bool `json:"applied"`
	}
	return json.Unmarshal(r.Result, &res) == nil && res.Applied
}

func insertGoxImport(sess *session, doc workspace.Doc) {
	pos, do := doc.GoxImportPos(sess.enc())
	if !do {
		return
	}
	sess.callClient(
		applyEdit,
		jsonGenerator.newInsertEdit(
			doc.SourceFile().URI(),
			pos,
			"\n\nimport \"github.com/doors-dev/gox\"",
			"GoX imported",
		),
	)
}
